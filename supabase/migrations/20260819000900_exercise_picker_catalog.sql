create or replace function public.get_exercise_picker_catalog()
returns table (
  id uuid,
  canonical_name text,
  measurement_type text,
  primary_muscle_group text,
  workout_type text,
  aliases text[],
  last_used_at timestamptz
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    e.id,
    e.canonical_name,
    e.measurement_type::text,
    e.primary_muscle_group,
    e.workout_type,
    e.aliases,
    recent.last_used_at
  from public.exercise_catalog e
  left join (
    select we.exercise_id, max(w.started_at) as last_used_at
    from public.workout_exercises we
    join public.workout_sessions w on w.id = we.workout_id
    where w.user_id = auth.uid()
      and w.category = 'STRENGTH'
      and w.source = 'IN_APP'
      and w.status = 'COMPLETED'
    group by we.exercise_id
  ) recent on recent.exercise_id = e.id
  where auth.uid() is not null
    and e.active = true
  order by recent.last_used_at desc nulls last, e.canonical_name asc;
$$;

revoke all on function public.get_exercise_picker_catalog() from public, anon, authenticated;
grant execute on function public.get_exercise_picker_catalog() to authenticated;
