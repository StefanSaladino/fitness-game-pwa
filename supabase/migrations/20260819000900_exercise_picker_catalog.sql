-- Workout Game PWA — Phase 6.1C / 6.2 exercise picker metadata (v0.4.2)
-- Makes the canonical catalogue self-contained, browsable by muscle/workout type,
-- alias-aware, and capable of returning user-specific recents.

alter table public.exercise_catalog
  add column if not exists primary_muscle_group text not null default 'OTHER',
  add column if not exists workout_type text not null default 'OTHER',
  add column if not exists aliases text[] not null default array[]::text[];

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'exercise_catalog_primary_muscle_group_check'
      and conrelid = 'public.exercise_catalog'::regclass
  ) then
    alter table public.exercise_catalog
      add constraint exercise_catalog_primary_muscle_group_check
      check (primary_muscle_group in (
        'CHEST','BACK','SHOULDERS','BICEPS','TRICEPS','QUADS','HAMSTRINGS',
        'GLUTES','CALVES','CORE','FOREARMS_GRIP','NECK','FULL_BODY','OTHER'
      ));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'exercise_catalog_workout_type_check'
      and conrelid = 'public.exercise_catalog'::regclass
  ) then
    alter table public.exercise_catalog
      add constraint exercise_catalog_workout_type_check
      check (workout_type in (
        'BARBELL','DUMBBELL','KETTLEBELL','MACHINE','CABLE','BODYWEIGHT','ISOMETRIC',
        'PLYOMETRIC','MEDICINE_BALL','LANDMINE','BAND','STRONGMAN_CARRY_SLED',
        'OLYMPIC_POWER','SPECIALTY','OTHER'
      ));
  end if;
end;
$$;

